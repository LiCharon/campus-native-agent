# 近重复检测阈值（字符相似度，difflib.SequenceMatcher.ratio）
# - ERROR >= 0.85：几乎肯定是同主题换种说法（如 VPN 0.97、洗衣/洗衣机 0.93）→ 必须合并
# - WARN 0.55~0.85：疑似相似（含「X丢了怎么补办」这类模板撞车的不同主题）→ 告警人工复核
_NEAR_ERROR = 0.85
_NEAR_WARN = 0.55
_SEED_WARN = 0.80    # 与通用种子比对的告警阈值（降噪：只报强兄弟占位）

# 归一化：去空白与标点，转小写，使「宿舍空调怎么租？」与「宿舍空调租赁怎么办理？」可比对
_PUNCT_RE = re.compile(
    r"[\s，。？！、；：\"'（）()「」【】《》…—\-·.,?!;:\"'`()\[\]{}<>~`@#$%^&*_+=|\\/]"
)


def _norm(s: str) -> str:
    return _PUNCT_RE.sub("", s).lower()


def _similar(a: str, b: str) -> float:
    """字符级相似度（0~1）。用于近重复检测；纯 stdlib，无需任何外部依赖。"""
    return difflib.SequenceMatcher(None, _norm(a), _norm(b)).ratio()


def main() -> int:
    out_path = Path(__file__).resolve().parent.parent / "config" / "zjut_local_data.json"

    # ---- 校验 ----
    seen: set[str] = set()
    dups: list[str] = []
    bad_domain: list[str] = []
    empty: list[str] = []
    questions: list[str] = []
    for domain, keywords, question, ktype, answer in _DATA:
        if domain not in _DOMAINS:
            bad_domain.append(question)
        if not (keywords and question and ktype and answer):
            empty.append(question)
        if question in seen:
            dups.append(question)
        seen.add(question)
        questions.append(question)

    # 近重复检测（字符相似度，跨域也查——避免同一话题分散到不同域）
    near_err: list[str] = []
    near_warn: list[str] = []
    for i in range(len(questions)):
        for j in range(i + 1, len(questions)):
            score = _similar(questions[i], questions[j])
            pair = f"  {score:.2f}  「{questions[i]}」 ⇔ 「{questions[j]}」"
            if score >= _NEAR_ERROR:
                near_err.append(pair)
            elif score >= _NEAR_WARN:
                near_warn.append(pair)

    # 与通用种子 seed.py 近重复（告警：可能在校内留占位）
    try:
        sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
        from campus_desk.db.seed import _KNOWLEDGE
        generic_q = [q for (_, _, q, _, _) in _KNOWLEDGE]
        seed_warn: list[str] = []
        for q in questions:
            for gq in generic_q:
                score = _similar(q, gq)
                if score >= _SEED_WARN:
                    seed_warn.append(f"  {score:.2f}  「{q}」 ⇔ 通用种子「{gq}」")
    except Exception as e:  # noqa: BLE001
        seed_warn = [f"  (跳过通用种子比对: {e})"]

    if bad_domain:
        raise SystemExit(f"[校验失败] 以下条目 domain 不在白名单: {bad_domain}")
    if empty:
        raise SystemExit(f"[校验失败] 以下条目存在空字段: {empty}")
    if dups:
        raise SystemExit(f"[校验失败] 重复 question: {dups}")
    if near_err:
        raise SystemExit(
            "[校验失败] 检测到近重复 question（请用合并成一条更完整的问句，避免主题重复）：\n"
            + "\n".join(near_err)
        )
    if near_warn:
        print("[校验警告] 以下疑似相近 question，请人工复核：")
        print("\n".join(near_warn))
    if seed_warn:
        print("[校验警告] 以下本地 question 与通用种子近重复（若意在覆盖占位请用完全相同问句）：")
        print("\n".join(seed_warn))

    # ---- 组装并按 domain 排序，便于审阅 ----
    records = [
        {"domain": d, "keywords": k, "question": q, "type": t, "answer": a}
        for (d, k, q, t, a) in _DATA
    ]
    records.sort(key=lambda r: (_DOMAINS.index(r["domain"]), r["question"]))

    out_path.write_text(
        json.dumps(records, ensure_ascii=False, indent=2, sort_keys=False),
        encoding="utf-8",
    )

    counter = Counter(r["domain"] for r in records)
    print(f"[build_zjut_local] 已写入 {out_path}")
    print(f"[build_zjut_local] 共 {len(records)} 条，覆盖 {len(counter)} 个领域：")
    for d in _DOMAINS:
        print(f"    {d}: {counter.get(d, 0)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
